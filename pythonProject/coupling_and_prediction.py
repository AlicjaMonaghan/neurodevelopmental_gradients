# Load the structure-function coupling estimates for the referred portion of CALM and NKI
coupling_df = pd.read_csv('data/structure.function/coupling.data.df.csv')
# Add a column indicating neurotypicality
coupling_df['neurotypicality'] = np.where(coupling_df['dataset'] == "calm", "neurodivergent", "neurotypical")
# Retain data from the baseline time points
coupling_df = coupling_df[coupling_df.timepoint.isin(['baseline', 'bas1'])]
# Subset by the columns we need for modelling
common_columns = ['dataset', 'sex', 'meanfwd', 'scan_age', 'Vis', 'SomMot', 'DorsAttn', 'SalVentAttn',
     'Limbic', 'Cont', 'Default', 'global', 'neurotypicality']
complete_coupling_df = pd.concat([coupling_df[common_columns], calm_neurotypical_coupling_pd[common_columns]])
complete_coupling_df.rename(columns={'global': 'global_coupling'}, inplace=True)
# Re-code sex as a categorical integer i.e. M = 0 and F = 1
complete_coupling_df.sex = complete_coupling_df.sex.replace({'M': 0, 'F': 1})
# Convert columns to categorical, where appropriate, and Z-score numeric columns
categorical_columns = ['sex', 'neurotypicality', 'dataset']
complete_coupling_df[categorical_columns] = complete_coupling_df[categorical_columns].astype('category')
numeric_columns = complete_coupling_df.select_dtypes(include='number').columns
complete_coupling_df[numeric_columns] = complete_coupling_df[numeric_columns].apply(zscore)
# Conduct a series of GLMs where we predict mean coupling using scan age, mean FWD, sex, neurotypicality and dataset.
coupling_divisions = ['global_coupling', 'SomMot', 'Vis', 'DorsAttn', 'SalVentAttn', 'Limbic', 'Cont', 'Default']
coupling_pvalues = np.zeros((len(coupling_divisions), 2))
for division_idx, division in enumerate(coupling_divisions):
    formula = f'{division} ~ scan_age + sex + meanfwd + neurotypicality + dataset'
    coupling_glm = smf.glm(formula=formula, data=complete_coupling_df).fit()
    # Extract the coefficient and uncorrected p-value corresponding to neurotypicality
    neurotypicality_coef = coupling_glm.params['neurotypicality[T.neurotypical]']
    neurotypicality_pval = coupling_glm.pvalues['neurotypicality[T.neurotypical]']
    coupling_pvalues[division_idx, 0] = neurotypicality_pval
    # Calculate Cohen's D as an effect size measure from the t-statistic
    neurotypicality_tstat = coupling_glm.tvalues['neurotypicality[T.neurotypical]']
    group_sample_sizes = complete_coupling_df.neurotypicality.value_counts()
    effect_size = compute_effsize_from_t(neurotypicality_tstat, group_sample_sizes.iloc[0], group_sample_sizes.iloc[1])
    print(f'{division}: neurotypicality coefficient of {np.round(neurotypicality_coef,3)}, '
          f' uncorrected p-value of {np.round(neurotypicality_pval, 3)}, and d of {np.round(effect_size, 3)}')
