def manifold_coupling(structural_gradient, functional_gradient):
    # For each modality, calculate the Euclidean distance between each node and all others within manifold space.
    nroi = structural_gradient.shape[0]
    within_manifold_nodal_euclidean = np.zeros((nroi, nroi, 2))
    within_manifold_nodal_euclidean[:, :, 0] = cdist(structural_gradient, structural_gradient)
    within_manifold_nodal_euclidean[:, :, 1] = cdist(functional_gradient, functional_gradient)
    # Calculate the correlation coefficient between each set of Euclidean distances (modality-specific) for each node.
    nodal_coupling = np.zeros(nroi)
    for roi in range(nroi):
        nodal_coupling[roi] = spearmanr(
            within_manifold_nodal_euclidean[roi, :, 0], within_manifold_nodal_euclidean[roi, :, 1])[0]
    return nodal_coupling, within_manifold_nodal_euclidean


