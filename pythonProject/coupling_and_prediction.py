# Load the group-level consensus structural and functional connectome for CALM
calm_consensus = loadmat('data/calm/connectomes/consensus.mat', simplify_cells=True)['consensus']
calm_sc_consensus = calm_consensus['sc']['referred']['weighted']['schaefer200x7']
calm_fc_consensus = calm_consensus['fc']['referred']['weighted']['schaefer200x7']
# Load the group-level gradients for the referred CALM subset
calm_referred_gradients = loadmat('data/calm.nki.group.gradients.mat', squeeze_me=True)['calm']['referred']
# Load the gradients for the neurotypical portion of CALM, and the associated meta-data
calm_neurotypical_gradients = loadmat('data/calm/dme/non-referred_schaefer200x7_baseline.mat')
calm_sc_master = pd.read_excel('data/calm/Alicja_calm_sc_master.xlsx')
calm_fc_master = pd.read_excel('data/calm/Alicja_calm_fc_master.xlsx')
# Load the Schaefer 200-node parcellation coordinates and calculate Euclidean distance
schaefer200_mat = loadmat('data/schaefer200x7_1mm_info.mat', squeeze_me=True)['schaefer200x7_1mm_info']
hemiid = np.zeros(200)
hemiid[100:] = 1
mni_coordinates = np.zeros((200, 3))
mni_coordinates[:, 0] = schaefer200_mat['x_mni'].item()
mni_coordinates[:, 1] = schaefer200_mat['y_mni'].item()
mni_coordinates[:, 2] = schaefer200_mat['z_mni'].item()
euclidean_distance = squareform(pdist(mni_coordinates, 'euclidean'))
# Load the Yeo network assignments for the Schaefer 200-node parcellation
yeo_assignments = pd.read_csv('data/schaefer200_yeo7_labels.csv')
# Load the indices of the rotated (null) maps generated by the Vasa method (2018, Cerebral Cortex)
rotated_parcellation = readRDS('data/rotated.parcellation.rds')
# Select the first 1000 spins for brevity. Subtract 1 to account for zero-indexing in Python
rotated_parcellation = np.array(rotated_parcellation)[:, 0:1000].astype(int) - 1
# Calculate communicability of structural connectivity
calm_communicability = communicability_wei(calm_sc_consensus)
# Get the shortest path length of the structural connectome
spl_mat, _ = distance_wei_floyd(euclidean_distance)
# Initialise an array which will hold nodal coupling values across 4 measures: the first is our manifold eccentricity,
# the second is the multi-linear regression model developed by Vazquez-Rodriguez and colleagues (2019, PNAS), the
# third in the correlation coefficient model of raw connectomes developed by Baum and colleagues (2020, PNAS), whilst
# the fourth is the correlation coefficient model of raw functional connectomes with structural gradients developed by
# Park and colleagues (2022, PNAS). The multi-linear regression model didn't threshold matrices. The Baum method applied
# a consistency-based thresholding measure to achieve a density of around 55% for the average structural connectome.
# Park and colleagues (2022) applied row-wise 10% thresholding for the functional connectome.
nodal_coupling = np.zeros((200, 4))
euclidean_manifold_coupling = manifold_coupling(calm_referred_gradients.item()[0,:,:],calm_referred_gradients.item()[1,:,:])
nodal_coupling[:, 0] = euclidean_manifold_coupling[0]
for node in range(200):
    # Now calculate SF-coupling using the method developed by Vazquez-Rodriguez and colleagues (2019, PNAS)
    lin_reg = LinearRegression()
    predictors = np.column_stack((euclidean_distance[node, :], calm_communicability[node, :], spl_mat[node, :]))
    yhat = lin_reg.fit(predictors, calm_fc_consensus[node, :]).predict(predictors)
    SS_Residual = sum((calm_fc_consensus[node, :] - yhat) ** 2)
    SS_Total = sum((calm_fc_consensus[node, :] - np.mean(calm_fc_consensus[node, :])) ** 2)
    r_squared = 1 - (float(SS_Residual)) / SS_Total
    nodal_coupling[node, 1] = (1 - (1 - r_squared) * (len(calm_fc_consensus[node, :]) - 1) /
                               (len(calm_fc_consensus[node, :]) - predictors.shape[1] - 1))
    # Calculate coupling using the method developed by Baum and colleagues (2020, PNAS)
    nodal_coupling[node, 2] = spearmanr(calm_sc_consensus[node, :], calm_fc_consensus[node, :])[0]
    # Calculate coupling using the method developed by Park and colleagues (2022, PNAS)
    nodal_coupling[node, 3] = spearmanr(euclidean_manifold_coupling[1][node,:,0], calm_fc_consensus[node,:])[0]
# Create a data frame to store the nodal coupling coefficients across the 4 metrics. Take the absolute of each metric as
# the metric from Park and colleagues (2022) is negatively correlated to all other metrics, potentially due to the
# combination of correlations of Euclidean distances and raw FC, whilst the other metrics all operate in the same space.
nodal_coupling = abs(nodal_coupling)
nodal_coupling_pd = pd.DataFrame(data=nodal_coupling, columns=['eLife.measure', 'baum', 'vazquez', 'park'])
# Add the region names for the Schaefer 200-node 7-network parcellation
nodal_coupling_pd['region'] = schaefer200_mat['name']
# Merge with the sensorimotor-association axis ranks, initially developed by Sydnor and colleagues (2021, Neuron) and
# taken from Audrey Luo's GitHub repository for her 2024 Nature Communications paper titled "Functional connectivity
# development along the sensorimotor-association axis enhances the cortical hierarchy".
SA_axis = pd.read_csv('data/figure1b_SAaxis.csv')
nodal_coupling_pd = nodal_coupling_pd.merge(SA_axis[['SA.axis_rank', 'region']], on='region')
nodal_coupling_pd.to_csv('data/structure.function/nodal.coupling.comparison.csv', index=None)
# Correlate each of the 4 metrics with each other: Initialise arrays to hold the correlation coefficients (the first two
# slices) and p-values derived from spin tests (the third slice).
coupling_comparison_array = np.zeros((4, 4, 2))
for i in range(4):
    for j in range(4):
        # Apply the spun indices to the empirical data to derive null maps
        null_values = np.zeros(rotated_parcellation.shape)
        for spin in range(rotated_parcellation.shape[1]):
            null_values[:, spin] = nodal_coupling[:, j][rotated_parcellation[:, spin]]
        coupling_comparison = compare_images(
            nodal_coupling[:, i], nodal_coupling[:, j], nulls=null_values, metric='spearmanr')
        coupling_comparison_array[i, j, :] = coupling_comparison
# Correlate each of the 4 metrics with the SA-axis! The first slice of the array holds the correlation coefficients,
# whilst the second slice holds the spin-test p-values.
coupling_SA_array = np.zeros((4, 2))
for i in range(4):
    null_values = np.zeros(rotated_parcellation.shape)
    for spin in range(rotated_parcellation.shape[1]):
        null_values[:, spin] = nodal_coupling[:, i][rotated_parcellation[:, spin]]
    coupling_SA_array[i, :] = compare_images(
        nodal_coupling[:, i], nodal_coupling_pd['SA.axis_rank'], nulls=null_values, metric='spearmanr')
# Save the first slice of this array (correlation coefficients) to visualise as a lolly plot in R! Put a '\n' between
# the labels and the dates, so that they render across separate lines.
coupling_SA_pd = pd.DataFrame(
    {'measure': ['eLife\n(2025)', 'PNAS\n(2020)', 'PNAS\n(2019)', 'PNAS\n(2022)'], 'corr': coupling_SA_array[:,0]})
coupling_SA_pd.to_csv('data/structure.function/coupling_SA_alignment.csv', index=None)
# Conduct a series of two-tailed Steiger tests to compare the magnitude of the correlation between our novel metric and
# the manifold-based metric, with that of the novel metric and the raw connectome measures.
for i in range(2):
    steiger_result = dependent_corr(xy=coupling_comparison_array[0, 3, 0], xz=coupling_comparison_array[0, i+1, 0],
                                  yz=coupling_comparison_array[3, i+1, 0], n=200)
    print(f'Relation of correlation between novel metric and manifold metric to novel metric and'
          f' {nodal_coupling_pd.columns[i+1]}: {steiger_result[0]:.3f} and p-value of {steiger_result[1]:.3f}')

# Using a series of two-tailed Steiger tests, examine whether the correlation between the SA axis and the novel metric
# is stronger than the relationship between the SA axis and the three other metrics! Degrees of freedom are n_region-2.
for i in range(3):
    xy = spearmanr(nodal_coupling_pd['eLife.measure'], nodal_coupling_pd['SA.axis_rank'])[0]
    xz = spearmanr(nodal_coupling_pd['eLife.measure'], nodal_coupling_pd.iloc[:, i+1])[0]
    yz = spearmanr(nodal_coupling_pd['SA.axis_rank'], nodal_coupling_pd.iloc[:, i+1])[0]
    SA_comparison = dependent_corr(xy, xz, yz, n=200)
    print(f'Comparison with SA-axis and {nodal_coupling_pd.columns[i+1]} correlation: Z-statistic of'
          f' {SA_comparison[0]:.3f} and p-value of {SA_comparison[1]:.3f}')

