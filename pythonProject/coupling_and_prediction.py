# Load the group-level consensus structural and functional connectome for CALM
calm_consensus = loadmat('data/calm/connectomes/consensus.mat', simplify_cells=True)['consensus']
calm_sc_consensus = calm_consensus['sc']['referred']['weighted']['schaefer200x7']
calm_fc_consensus = calm_consensus['fc']['referred']['weighted']['schaefer200x7']
# Load the group-level gradients for the referred CALM subset
calm_referred_gradients = loadmat('data/calm.nki.group.gradients.mat', squeeze_me=True)['calm']['referred']
# Load the Schaefer 200-node parcellation coordinates and calculate Euclidean distance
schaefer200_mat = loadmat('data/schaefer200x7_1mm_info.mat', squeeze_me=True)['schaefer200x7_1mm_info']
hemiid = np.zeros((200))
hemiid[100:] = 1
mni_coordinates = np.zeros((200, 3))
mni_coordinates[:, 0] = schaefer200_mat['x_mni'].item()
mni_coordinates[:, 1] = schaefer200_mat['y_mni'].item()
mni_coordinates[:, 2] = schaefer200_mat['z_mni'].item()
euclidean_distance = squareform(pdist(mni_coordinates, 'euclidean'))
# Load the indices of the rotated (null) maps generated by the Vasa method (2018, Cerebral Cortex)
rotated_parcellation = readRDS('data/rotated.parcellation.rds')
# Select the first 1000 spins for brevity. Subtract 1 to account for zero-indexing in Python
rotated_parcellation = np.array(rotated_parcellation)[:,0:1000].astype(int) - 1
# Calculate communicability of structural connectivity
calm_communicability = communicability_wei(calm_sc_consensus)
# Get the shortest path length of the structural connectome
spl_mat, _ = distance_wei_floyd(euclidean_distance)
# Initialise an array which will hold nodal coupling values across 3 measures: the first is our manifold eccentricity,
# the second is the multi-linear regression model developed by Vazquez-Rodriguez and colleagues (2019, PNAS), and the
# third in the correlation coefficient model developed by Baum and colleagues (2020, PNAS).
nodal_coupling = np.zeros((200, 3))
# For each modality, calculate the Euclidean distance between each node and all others within manifold space.
within_manifold_nodal_euclidean = np.zeros((200, 200, 2))
for modality in range(2):
    within_manifold_nodal_euclidean[:, :, modality] = cdist(
        calm_referred_gradients.item()[modality, :, :], calm_referred_gradients.item()[modality, :, :])
# Calculate the correlation coefficient between each set of Euclidean distances (modality-specific) for each node.
for node in range(200):
    nodal_coupling[node, 0] = spearmanr(
        within_manifold_nodal_euclidean[node, :, 0], within_manifold_nodal_euclidean[node, :, 1])[0]
    # Now calculate SF-coupling using the method developed by Vazquez-Rodriguez and colleagues (2019, PNAS)
    lin_reg = LinearRegression()
    predictors = np.column_stack((euclidean_distance[node, :], calm_communicability[node, :], spl_mat[node, :]))
    yhat = lin_reg.fit(predictors, calm_fc_consensus[node, :]).predict(predictors)
    SS_Residual = sum((calm_fc_consensus[node, :] - yhat) ** 2)
    SS_Total = sum((calm_fc_consensus[node, :] - np.mean(calm_fc_consensus[node, :])) ** 2)
    r_squared = 1 - (float(SS_Residual)) / SS_Total
    nodal_coupling[node, 1] = (1 - (1 - r_squared) * (len(calm_fc_consensus[node, :]) - 1) /
                               (len(calm_fc_consensus[node, :]) - predictors.shape[1] - 1))
    # Calculate coupling using the method developed by Baum and colleagues (2020, PNAS)
    nodal_coupling[node, 2] = spearmanr(calm_sc_consensus[node, :], calm_fc_consensus[node, :])[0]
baum_vazquez_pspin = compare_images(
    nodal_coupling[:, 1], nodal_coupling[:, 2], nulls=rotated_parcellation, metric='spearmanr')
vazquez_novel_pspin = compare_images(
    nodal_coupling[:, 2], nodal_coupling[:, 0], nulls=rotated_parcellation, metric='spearmanr')
baum_novel_pspin = compare_images(
    nodal_coupling[:, 1], nodal_coupling[:, 0], nulls=rotated_parcellation, metric='spearmanr')
# Examine whether our novel metric is more closely aligned to either of the established metrics.
steiger_baum_vazquez = dependent_corr(xy=baum_novel_pspin[0], xz=vazquez_novel_pspin[0], yz=baum_vazquez_pspin[0], n=200)
# Create a data frame to summarize the different methods
nodal_coupling_pd = pd.DataFrame(zscore(nodal_coupling), columns=['eLife.measure', 'baum.2020', 'vazquez.2019'])
nodal_coupling_pd['region'] = schaefer200_mat['name'].item()
# Measure the association of each coupling metric with the sensorimotor-association axis developed by Sydnor and
# colleagues (2021, Neuron)
schaefer32k = fetch_schaefer2018('fslr32k', data_dir='data')['200Parcels7Networks']
parc32k = Parcellater(dlabel_to_gifti(schaefer32k), 'fsLR')
SA_axis = parc32k.fit_transform(
    ['data/SensorimotorAssociation_Axis_RH.fslr32k.func.gii',
     'data/SensorimotorAssociation_Axis_RH.fslr32k.func.gii'], 'fsLR', ignore_background_data=True)
# Add the SA-axis ranks to the nodal coupling data frame for visualisation in R
nodal_coupling_pd['SA'] = SA_axis
nodal_coupling_pd.to_csv('data/structure.function/nodal.coupling.comparison.csv', index=None)
# Correlate each metric with the S-A axis and store the correlation coefficients
SA_association_output = np.zeros((3, 2))
for i in range(3):
    SA_association_output[i, :] = compare_images(
        nodal_coupling_pd.iloc[:, i], nodal_coupling_pd.SA, nulls=rotated_parcellation, metric='spearmanr')
# Show that the alignment between our metric and the SA axis is stronger than the other two metrics
baum_novel_SA_comparison = dependent_corr(
    SA_association_output[0,0], SA_association_output[1,0], baum_novel_pspin[0], n=200)
vazquez_novel_SA_comparison = dependent_corr(
    SA_association_output[0,0], SA_association_output[2,0], vazquez_novel_pspin[0], n=200)

