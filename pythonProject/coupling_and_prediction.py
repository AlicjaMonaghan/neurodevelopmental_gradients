# For motion, calculate the mean motion across structural and functional scans
calm_neurotypical_coupling_pd = calm_neurotypical_coupling_pd.merge(
    calm_sc_master[calm_sc_master.Referred == 0][['BIDS', 'meanFWD']]).rename(columns={'meanFWD': 'SC_meanFWD'})
calm_neurotypical_coupling_pd['meanFWD'] = calm_neurotypical_coupling_pd[['FC_meanFWD', 'SC_meanFWD']].mean(axis=1)
# Add columns representing data set and neurotypicality
calm_neurotypical_coupling_pd['dataset'] = 'calm'
calm_neurotypical_coupling_pd['neurotypicality'] = 'neurotypical'
# Rename columns for easier merging!
calm_neurotypical_coupling_pd.rename(columns={'Sex': 'sex', 'meanFWD': 'meanfwd'}, inplace=True)
# Save for GAMM modelling in R!
calm_neurotypical_coupling_pd.to_csv('data/calm/structure.function/calm_neurotypical_coupling.csv')

